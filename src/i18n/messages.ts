export type MessageKey = keyof (typeof messages)['zh-CN'];
export type MessageParams = Record<string, string | number>;

function interpolate(template: string, params?: MessageParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? ''));
}

export function getMessage(key: MessageKey, locale: Locale = defaultLocale, params?: MessageParams): string {
  return interpolate(messages[locale][key], params);
}

export function createTranslator(locale: Locale = defaultLocale) {
  return (key: MessageKey, params?: MessageParams) => getMessage(key, locale, params);
}
